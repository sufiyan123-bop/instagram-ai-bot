ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "output"
MODEL = os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite")
BRAND = os.getenv("BRAND_NAME", "FACT DAILY")[:20].upper()
SIDE = 1080
Y_PANEL = 565
TOPICS = [
    "Octopus", "Honey bee", "Venus", "Jupiter", "Saturn", "Mars",
    "Great Barrier Reef", "Antarctica", "Hummingbird", "Koala",
    "Blue whale", "Giant panda", "Lightning", "Solar eclipse",
    "Aurora", "Volcano", "Giraffe", "Dolphin", "Penguin",
    "Red panda", "Elephant", "Chameleon", "Axolotl", "Coral reef",
    "Baobab", "Mount Everest", "Moon", "Neptune", "Red fox", "Owl",
]
HTTP = requests.Session()
HTTP.headers.update({"User-Agent": "FactDailyInstagramBot/2.0 (educational project; contact: https://github.com/sufiyan123-bop/instagram-ai-bot)"})


def get_verified_source():
    """Select a Wikipedia article with factual text and a photo."""
    for name in random.sample(TOPICS, len(TOPICS)):
        endpoint = "https://en.wikipedia.org/api/rest_v1/page/summary/" + quote(name.replace(" ", "_"))
        try:
            response = HTTP.get(endpoint, timeout=20, headers={"Accept": "application/json"})
            response.raise_for_status()
            data = response.json()
            extract = (data.get("extract") or "").strip()
            possible_photos = []
            for kind in ("originalimage", "thumbnail"):
                address = (data.get(kind) or {}).get("source", "")
                if address.lower().split("?")[0].endswith((".jpg", ".jpeg", ".png", ".webp")):
                    if address not in possible_photos:
                        possible_photos.append(address)
            if len(extract) < 180 or data.get("type") == "disambiguation" or not possible_photos:
                continue
            source = data.get("content_urls", {}).get("desktop", {}).get("page", endpoint)
            return data.get("title", name), extract[:2600], source, possible_photos
        except (requests.RequestException, ValueError, KeyError):
            continue
    raise RuntimeError("Wikipedia photo/source unavailable. Please retry the workflow.")


def generate_mixed_copy(title, extract, source):
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError("Missing GEMINI_API_KEY in GitHub Actions secrets.")
    prompt = f"""Create an educational 2-slide Instagram carousel based ONLY on the Wikipedia excerpt.
Write natural, correctly spelled Hindi in DEVANAGARI mixed with English words in LATIN letters.
Example style: 'Octopus के पास 3 दिल होते हैं!' (NOT only English or only roman Hinglish).
Both the 'fact' and 'explanation' MUST include Devanagari AND English letters.
Use short, dramatic yet truthful phrases. NO unverified claims, no made-up numbers,
no emojis, no hashtags, no markdown, no URLs inside fields. Do NOT force octopus facts
if the topic is different. Stick to statements explicitly supported by this excerpt.

Return ONLY JSON with four string fields:
- hook: catchy Hindi heading, 12-36 characters, e.g. 'क्या आप जानते हैं?'
- fact: ONE surprising sourced statement in Hindi-English mix, 20-75 characters.
- explanation: a different brief detail supported by source, Hindi-English mix, 45-115 characters.
- caption: 1-2 short Hindi-English sentences, 25-160 characters.

Topic: {title}
Source: {source}
Wikipedia excerpt: {extract}
"""
    client = genai.Client(api_key=api_key)
    result = client.models.generate_content(
        model=MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            temperature=0.25,
            response_mime_type="application/json",
        ),
    )
    if not result.text:
        raise RuntimeError("Gemini returned empty content. Check model name and quota.")
    try:
        data = json.loads(result.text)
    except ValueError as exc:
        raise RuntimeError("Gemini returned invalid JSON. Retry preview.") from exc
    limits = {"hook": (10, 48), "fact": (15, 85), "explanation": (30, 130), "caption": (20, 200)}
    for field, (minimum, maximum) in limits.items():
        value = str(data.get(field, "")).strip()
        if not minimum <= len(value) <= maximum:
            raise RuntimeError(f"Gemini {field} length invalid; retry preview.")
        data[field] = value
    for field in ("fact", "explanation"):
        if not re.search(r"[\u0900-\u097f]", data[field]) or not re.search(r"[A-Za-z]", data[field]):
            raise RuntimeError(f"Gemini {field} is not Hindi + English mixed; retry preview.")
    return data


def download_photo(urls):
    """Try an original photo, then a smaller thumbnail if needed."""
    for url in urls:
        try:
            with HTTP.get(url, timeout=45, stream=True) as res:
                res.raise_for_status()
                raw = bytearray()
                for part in res.iter_content(65536):
                    raw.extend(part)
                    if len(raw) > 22 * 1024 * 1024:
                        raise ValueError("Source image too large")
            with Image.open(io.BytesIO(raw)) as im:
                im.load()
                if im.width < 300 or im.height < 260:
                    raise ValueError("Source image too small")
                return ImageOps.exif_transpose(im).convert("RGB"), url
        except (requests.RequestException, ValueError, OSError) as exc:
            print("Skipping unsuitable image:", type(exc).__name__)
            continue
    raise RuntimeError("No usable topic photo downloaded. Retry preview.")


def load_font(size, bold=False, script="hi"):
    """Load a font for one writing system; never display Roman letters as boxes."""
    if script == "en":
        latin = ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold
                 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
        return ImageFont.truetype(latin, size)

    if not features.check("raqm"):
        raise RuntimeError("Pillow libraqm is required for correct Hindi shaping.")
    names = [
        "/usr/share/fonts/truetype/noto/NotoSansDevanagari-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/noto/NotoSansDevanagari-Regular.ttf",
        "/usr/share/fonts/truetype/noto/NotoSansDevanagariUI-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/noto/NotoSansDevanagariUI-Regular.ttf",
    ]
    path = next((Path(p) for p in names if Path(p).is_file()), None)
    if path is None:
        try:
            font_match = subprocess.check_output(
                ["fc-match", "-f", "%{file}", "Noto Sans Devanagari"], text=True, timeout=5
            ).strip()
            if "Devanagari" in font_match and Path(font_match).is_file():
                path = Path(font_match)
        except (OSError, subprocess.SubprocessError):
            pass
    if path is None:
        path = Path(tempfile.gettempdir()) / "autopost_noto_devanagari.ttf"
        if not path.is_file():
            font_url = (
                "https://raw.githubusercontent.com/google/fonts/main/ofl/"
                "notosansdevanagari/NotoSansDevanagari%5Bwdth%2Cwght%5D.ttf"
            )
            res = HTTP.get(font_url, timeout=35)
            res.raise_for_status()
            path.write_bytes(res.content)
    loaded = ImageFont.truetype(str(path), size, layout_engine=ImageFont.Layout.RAQM)
    try:
        axes = loaded.get_variation_axes()
        if axes:
            coordinates = []
            for axis in axes:
                axis_name = axis["name"].decode() if isinstance(axis["name"], bytes) else axis["name"]
                if "Weight" in axis_name:
                    coordinates.append(800 if bold else 500)
                else:
                    coordinates.append(axis["default"])
            loaded.set_variation_by_axes(coordinates)
    except (OSError, AttributeError, ValueError):
        pass
    return loaded


def center_fit(draw, text, y1, y2, width, size_start, color, max_lines, bold=True, highlight=False):
    """Compose mixed Latin + Devanagari on the same baseline with correct fonts."""
    for size in range(size_start, 25, -2):
        hindi_face = load_font(size, bold, script="hi")
        latin_face = load_font(int(size * 0.88), bold, script="en")
        space_width = draw.textlength(" ", font=latin_face)
        lines, line, used = [], [], 0.0
        for word in text.split():
            is_hindi = bool(re.search(r"[\u0900-\u097f]", word))
            face = hindi_face if is_hindi else latin_face
            word_width = draw.textlength(word, font=face, language="hi" if is_hindi else "en")
            need = (space_width if line else 0) + word_width
            if line and used + need > width:
                lines.append((line, used))
                line, used = [], 0.0
            if word_width > width:
                line = []; used = float("inf"); break
            line.append((word, face, word_width, is_hindi))
            used += (space_width if len(line) > 1 else 0) + word_width
        if line:
            lines.append((line, used))
        # Avoid a lonely final word like "हैं!" on its own line.
        if len(lines) >= 2 and len(lines[-1][0]) == 1 and len(lines[-2][0]) >= 3:
            previous_words, previous_width = lines[-2]
            last_words, last_width = lines[-1]
            moved = previous_words[-1]
            revised_last_width = moved[2] + space_width + last_width
            if revised_last_width <= width:
                lines[-2] = (previous_words[:-1], previous_width - space_width - moved[2])
                lines[-1] = ([moved] + last_words, revised_last_width)
        step = int(size * 1.42)
        if len(lines) > max_lines or len(lines) * step > y2 - y1 or used == float("inf"):
            continue
        baseline = y1 + (y2 - y1 - len(lines) * step) / 2 + int(size * 1.05)
        for words, line_width in lines:
            x = (SIDE - line_width) / 2
            for idx, (word, face, word_width, is_hindi) in enumerate(words):
                if idx:
                    x += space_width
                accent = bool(re.search(r"\d", word)) or word.strip("!?.।").upper() in {"BLUE", "COPPER"}
                ink = (255, 224, 35) if highlight and accent else color
                draw.text((round(x), round(baseline)), word, font=face, anchor="ls",
                          fill=ink, language="hi" if is_hindi else "en")
                x += word_width
            baseline += step
        return
    raise ValueError("Text does not fit the 1:1 image. Retry with shorter AI copy.")


def design_slide(position, photo, copy):
    """1080x1080 photo top / cinematic fade / black text block."""
    crop = ImageOps.fit(photo, (SIDE, Y_PANEL + 78), method=Image.Resampling.LANCZOS,
                        centering=(0.50 if position == 1 else 0.62, 0.47))
    crop = ImageEnhance.Contrast(crop).enhance(1.12)
    crop = ImageEnhance.Color(crop).enhance(1.18)
    slide = Image.new("RGB", (SIDE, SIDE), (7, 7, 9))
    slide.paste(crop, (0, 0))
    # Fade from the real image into the black lower panel.
    shade = Image.new("RGBA", (SIDE, SIDE), (0, 0, 0, 0))
    shader = ImageDraw.Draw(shade)
    for y in range(445, Y_PANEL + 100):
        alpha = int(255 * min(1.0, max(0, (y - 445) / (Y_PANEL + 75 - 445))))
        shader.line((0, y, SIDE, y), fill=(0, 0, 0, alpha), width=1)
    slide = Image.alpha_composite(slide.convert("RGBA"), shade).convert("RGB")
    d = ImageDraw.Draw(slide)
    yellow = (255, 224, 35)
    white = (252, 252, 250)
    cyan = (44, 209, 249)

    # Page marker at photo top-right.
    d.rounded_rectangle((905, 25, 1044, 92), radius=32, fill=(8, 10, 14))
    d.text((974, 61), f"{position}/2", font=load_font(35, True, script="en"),
           anchor="mm", fill=white)

    if position == 1:
        center_fit(d, copy["hook"], 588, 678, 990, 67, yellow, 2)
        center_fit(d, copy["fact"], 694, 918, 980, 76, white, 3, highlight=True)
        d.rounded_rectangle((392, 934, 688, 942), radius=4, fill=yellow)
        bottom = "SWIPE  >>>"
    else:
        center_fit(d, "और भी हैरानी की बात!", 584, 683, 1000, 57, yellow, 2)
        center_fit(d, copy["explanation"], 687, 918, 990, 58, white, 4, highlight=True)
        d.rounded_rectangle((392, 934, 688, 942), radius=4, fill=yellow)
        bottom = "SOURCE IN CAPTION"

    d.text((66, 1023), BRAND, font=load_font(24, True, script="en"), anchor="lm", fill=(200, 200, 200))
    d.text((1015, 1023), bottom, font=load_font(24, True, script="en"), anchor="rm", fill=cyan)
    OUTPUT.mkdir(exist_ok=True, parents=True)
    dst = OUTPUT / f"slide_{position}.jpg"
    slide.save(dst, format="JPEG", quality=93, optimize=True, subsampling=0)
    return dst


def main():
    print("Generating two square Hindi+English carousel images.")
    topic, excerpt, source, image_urls = get_verified_source()
    copy = generate_mixed_copy(topic, excerpt, source)
    photo, image_url = download_photo(image_urls)
    first = design_slide(1, photo, copy)
    second = design_slide(2, photo, copy)
    caption = (
        f"{copy['caption']}\n\nSource: {source}\n"
        f"Image source (check license/attribution): {image_url}\n\n"
        "#AmazingFacts #HindiFacts #Knowledge #Facts"
    )
    (OUTPUT / "caption.txt").write_text(caption, encoding="utf-8")
    (OUTPUT / "source_excerpt.txt").write_text(
        f"TOPIC: {topic}\nSOURCE: {source}\nIMAGE: {image_url}\n\n{excerpt}\n", encoding="utf-8"
    )
    print("SUCCESS:", first.name, second.name, "1080x1080")
    print("Preview and verify facts and image rights before auto-publishing.")


if __name__ == "__main__":
    main()

"""Create two 1:1 Hindi + Hinglish Instagram carousel images.

Output contract stays unchanged for the existing publisher:
    output/slide_1.jpg, output/slide_2.jpg, output/caption.txt

Pictures are downloaded from Wikipedia/Wikimedia, NOT generated by an image AI.
Check image licensing/attribution and generated facts before enabling auto-posting.
"""
